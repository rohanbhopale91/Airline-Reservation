import { jsPDF } from "jspdf";

import {
  durationLabel,
  formatDateTime,
  formatMoney,
  type Booking,
  type Flight,
} from "./airline";

export function buildTicketPdf(booking: Booking, flight: Flight) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const left = 48;
  const width = 499;

  doc.setFillColor(23, 30, 48);
  doc.rect(0, 0, 595, 120, "F");
  doc.setTextColor(244, 186, 84);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.text("SKYLINE AIR", left, 60);
  doc.setTextColor(235, 238, 245);
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.text("Electronic Ticket / Boarding Pass", left, 82);
  doc.setFontSize(20);
  doc.setFont("helvetica", "bold");
  doc.text(booking.pnr, left + width - doc.getTextWidth(booking.pnr), 60);
  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.text("PNR", left + width - doc.getTextWidth("PNR"), 78);

  doc.setTextColor(30, 36, 52);
  doc.setFontSize(28);
  doc.setFont("helvetica", "bold");
  doc.text(flight.origin, left, 190);
  doc.text(flight.destination, left + width - doc.getTextWidth(flight.destination), 190);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(flight.origin_city, left, 208);
  doc.text(flight.destination_city, left + width - doc.getTextWidth(flight.destination_city), 208);
  doc.setDrawColor(190, 196, 210);
  doc.line(left + 90, 182, left + width - 90, 182);
  doc.setFontSize(9);
  const dur = durationLabel(flight.depart_at, flight.arrive_at);
  doc.text(dur, 297 - doc.getTextWidth(dur) / 2, 176);

  const rows: Array<[string, string]> = [
    ["Passenger", booking.passenger_name],
    ["Email", booking.passenger_email],
    ["Flight", `${flight.flight_no} — ${flight.airline}`],
    ["Aircraft", flight.aircraft],
    ["Departure", formatDateTime(flight.depart_at)],
    ["Arrival", formatDateTime(flight.arrive_at)],
    ["Seat", booking.seat_no],
    ["Class", booking.cabin_class],
    ["Fare", formatMoney(Number(booking.fare))],
    ["Status", booking.status],
    ["Issued", formatDateTime(booking.created_at)],
  ];

  let y = 260;
  rows.forEach(([label, value], index) => {
    if (index % 2 === 0) {
      doc.setFillColor(243, 245, 249);
      doc.rect(left, y - 14, width, 26, "F");
    }
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(88, 96, 116);
    doc.text(label.toUpperCase(), left + 12, y + 3);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);
    doc.setTextColor(25, 30, 45);
    doc.text(String(value), left + 180, y + 3);
    y += 26;
  });

  doc.setDrawColor(200, 205, 218);
  doc.setLineDashPattern([4, 4], 0);
  doc.line(left, y + 18, left + width, y + 18);
  doc.setLineDashPattern([], 0);

  doc.setFontSize(9);
  doc.setTextColor(110, 118, 138);
  doc.text(
    "Boarding closes 25 minutes before departure. Carry a valid photo ID.",
    left,
    y + 44,
  );
  doc.text("Generated by Skyline Reservation System", left, y + 60);

  return doc;
}

export function downloadTicket(booking: Booking, flight: Flight) {
  buildTicketPdf(booking, flight).save(`ticket-${booking.pnr}.pdf`);
}
